#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { main, requireValue, ROOT } from "./lib.ts";

type Allow = [string, string, string, string[]];
type Transition = [string, string, string, string, string | null];
// dontaudit rules suppress the expected audit noise without granting the
// permission; the kernel avtab stores them as AVTAB_AUDITDENY, where a SET
// bit means "do not audit" (inverted relative to allow).
type DontAudit = [string, string, string, string[]];
type IoctlAllow = [string, string, string, number[]];

export function generate(source: string): string {
    const text = source.replace(/#.*$/gm, "").replace(/\s+/g, " ");
    const consumed: Array<[number, number]> = [];
    const collect = (expression: RegExp): RegExpMatchArray[] => {
        const matches = [...text.matchAll(expression)];
        for (const match of matches) consumed.push([match.index!, match.index! + match[0].length]);
        return matches;
    };
    const types = collect(/\btype\s+([a-z_0-9]+)\s*;/g).map((match) => match[1]);
    const attributes = new Map<string, string[]>();
    for (const match of collect(/\btypeattribute\s+([a-z_0-9]+)\s+([a-z_0-9]+)\s*;/g)) {
        attributes.set(match[1], [...(attributes.get(match[1]) ?? []), match[2]]);
    }
    const allows: Allow[] = collect(/\ballow\s+(\{[^}]*\}|[a-z_0-9]+)\s+(\{[^}]*\}|[a-z_0-9]+)\s*:\s*([a-z_0-9]+)\s*(\{[^}]*\}|[a-z_0-9]+)\s*;/g)
        .flatMap((match) => match[1].replace(/[{}]/g, "").trim().split(/\s+/).flatMap((sourceType) =>
            match[2].replace(/[{}]/g, "").trim().split(/\s+/).map((targetType) =>
                [sourceType, targetType, match[3], match[4].replace(/[{}]/g, "").trim().split(/\s+/)] as Allow)));
    const ioctls: IoctlAllow[] = collect(/\ballowxperm\s+([a-z_0-9]+)\s+([a-z_0-9]+)\s*:\s*(chr_file|blk_file)\s+ioctl\s*\{\s*((?:0x[0-9a-fA-F]{1,4}\s*)+)\}\s*;/g)
        .map((match) => [match[1], match[2], match[3], [...new Set(match[4].trim().split(/\s+/).map((value) => Number(value)))]]);
    const transitions: Transition[] = collect(/\btype_transition\s+([a-z_0-9]+)\s+([a-z_0-9]+)\s*:\s*([a-z_0-9]+)\s+([a-z_0-9]+)(?:\s+"([a-zA-Z0-9_.-]+)")?\s*;/g)
        .map((match) => [match[1], match[2], match[3], match[4], match[5] ?? null]);
    const dontaudits: DontAudit[] = collect(/\bdontaudit\s+(\{[^}]*\}|[a-z_0-9]+)\s+(\{[^}]*\}|[a-z_0-9]+)\s*:\s*([a-z_0-9]+)\s*(\{[^}]*\}|[a-z_0-9]+)\s*;/g)
        .flatMap((match) => match[1].replace(/[{}]/g, "").trim().split(/\s+/).flatMap((sourceType) =>
            match[2].replace(/[{}]/g, "").trim().split(/\s+/).map((targetType) =>
                [sourceType, targetType, match[3], match[4].replace(/[{}]/g, "").trim().split(/\s+/)] as DontAudit)));
    for (const match of collect(/\binit_daemon_domain\s*\(\s*([a-z_0-9]+)\s*\)\s*;?/g)) {
        transitions.push(["init", `${match[1]}_exec`, "process", match[1], null]);
    }
    const remainder = [...text].map((character, index) => consumed.some(([start, end]) => start <= index && index < end) ? " " : character).join("").trim();
    requireValue(!remainder, `unsupported statement(s) in voboost.te: ${remainder.replace(/\s+/g, " ").slice(0, 120)}`);
    const declared = new Set([...types, ...attributes.keys()]);
    for (const [sourceType, targetType] of [...allows, ...ioctls]) {
        for (const symbol of [sourceType, targetType]) {
            requireValue(!symbol.startsWith("voboost") || declared.has(symbol), `unknown local symbol ${symbol}`);
        }
    }
    const quoted = (value: string): string => JSON.stringify(value);
    const lines = [
        "/* generated by tools/gen-policy-rules.ts - DO NOT EDIT */",
        "",
        "#pragma once",
        "",
        `#define VR_TYPES_COUNT ${types.length}`,
        `#define VR_ALLOWS_COUNT ${allows.length}`,
        `#define VR_TRANSITIONS_COUNT ${transitions.length}`,
        `#define VR_DONTAUDITS_COUNT ${dontaudits.length}`,
        `#define VR_IOCTL_ALLOWS_COUNT ${ioctls.length}`,
        "",
        "typedef struct { const char *name; const char *const *attrs; unsigned attrs_len; } vr_type;",
        "typedef struct { const char *src, *tgt, *cls; const char *const *perms; unsigned perms_len; } vr_allow;",
        "typedef struct { const char *src, *tgt, *cls, *new_type, *filename; } vr_transition;",
        "typedef struct { const char *src, *tgt, *cls; const char *const *perms; unsigned perms_len; } vr_dontaudit;",
        "typedef struct { const char *src, *tgt, *cls; const unsigned short *commands; unsigned commands_len; } vr_ioctl_allow;",
        "",
    ];
    for (const name of types) {
        const values = attributes.get(name) ?? [];
        lines.push(`static const char *const vr_attrs_${name}[] = { ${values.length ? values.map(quoted).join(", ") : "0"} };`);
        lines.push(`static const unsigned vr_attrs_${name}_len = ${values.length};`);
    }
    lines.push("", "static const vr_type vr_types[] = {");
    for (const name of types) lines.push(`    { ${quoted(name)}, vr_attrs_${name}, vr_attrs_${name}_len },`);
    lines.push("};", "");
    allows.forEach(([, , , permissions], index) => lines.push(`static const char *const vr_perms_${index}[] = { ${permissions.map(quoted).join(", ")} };`));
    lines.push("", "static const vr_allow vr_allows[] = {");
    allows.forEach(([sourceType, targetType, klass, permissions], index) => lines.push(`    { ${quoted(sourceType)}, ${quoted(targetType)}, ${quoted(klass)}, vr_perms_${index}, ${permissions.length} },`));
    lines.push("};", "", "static const vr_transition vr_transitions[] = {");
    transitions.forEach(([sourceType, targetType, klass, newType, filename]) => lines.push(`    { ${quoted(sourceType)}, ${quoted(targetType)}, ${quoted(klass)}, ${quoted(newType)}, ${filename ? quoted(filename) : "0"} },`));
    lines.push("};", "");
    dontaudits.forEach(([, , , permissions], index) => lines.push(`static const char *const vr_dontaudit_perms_${index}[] = { ${permissions.map(quoted).join(", ")} };`));
    lines.push("", "static const vr_dontaudit vr_dontaudits[] = {");
    dontaudits.forEach(([sourceType, targetType, klass, permissions], index) => lines.push(`    { ${quoted(sourceType)}, ${quoted(targetType)}, ${quoted(klass)}, vr_dontaudit_perms_${index}, ${permissions.length} },`));
    lines.push("};", "");
    ioctls.forEach(([, , , commands], index) => lines.push(`static const unsigned short vr_ioctl_commands_${index}[] = { ${commands.map((value) => `0x${value.toString(16).padStart(4, "0")}`).join(", ")} };`));
    lines.push("", "static const vr_ioctl_allow vr_ioctl_allows[] = {");
    ioctls.forEach(([sourceType, targetType, klass, commands], index) => lines.push(`    { ${quoted(sourceType)}, ${quoted(targetType)}, ${quoted(klass)}, vr_ioctl_commands_${index}, ${commands.length} },`));
    lines.push("};", "");
    return lines.join("\n");
}

main(() => {
    const source = resolve(ROOT, "selinux/voboost.te");
    const destination = resolve(ROOT, "selinux/rules.gen.h");
    const generated = generate(readFileSync(source, "utf8"));
    writeFileSync(destination, generated, "utf8");
    console.log(`gen-policy-rules: wrote ${destination}`);
}, "gen-policy-rules");
